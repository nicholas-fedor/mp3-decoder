// TestSynthTables checks that the generated tables hold the window and the DCT's factors, or
// rewrites them with -update.
//
// Each tap must agree with the 9-decimal table to within its rounding. The factors must round
// exactly from 320 bits and agree with their cosines.
func TestSynthTables(t *testing.T) {
	want := windowFromUnits()
	factors := closedFactors()

	if *update {
		require.NoError(t, os.WriteFile(generatedFile, synthSource(t, &factors, &want), 0o644))

		return
	}

	t.Parallel()

	assert.Equal(t, want, window)
	assert.Equal(t, factors, lee)

	for tap, published := range publishedWindow {
		assert.InDelta(t, published, window[tap], 5.1e-10, "tap %d", tap)
	}

	at := 0

	for n := Subbands; n > 1; n /= 2 {
		for k := range n / 2 {
			// The factor and the cosine each round once, so their product is 1/2 within two roundings.
			assert.InDelta(t, 0.5, lee[at]*trig.Cos(2*k+1, 2*n), 2.3e-16, "%d points, factor %d", n, k)

			at++
		}
	}
}

// windowFromUnits builds the 512 taps from the first 257.
//
// Tap 512-i is tap i, negated unless i is a multiple of 64.
func windowFromUnits() [windowTaps]float64 {
	var out [windowTaps]float64

	for tap, units := range publishedUnits {
		value := float64(units) / (1 << 16)
		out[tap] = value

		if tap%vectorSize != 0 {
			value = -value
		}

		if tap != 0 {
			out[windowTaps-tap] = value
		}
	}

	return out
}

// closedFactors computes the factors 1/(2 cos(π(2k+1)/(2n))) of each split of the DCT, for n of
// 32, 16, 8, 4 and 2 in turn.
func closedFactors() [dctFactors]float64 {
	var out [dctFactors]float64

	at := 0

	for n := Subbands; n > 1; n /= 2 {
		for k := range n / 2 {
			out[at] = trig.Sec(2*k+1, 2*n) / 2
			at++
		}
	}

	return out
}

// synthSource writes the generated file for the tables.
func synthSource(t *testing.T, factors *[dctFactors]float64, taps *[windowTaps]float64) []byte {
	t.Helper()

	var b bytes.Buffer

	row := func(values []float64) {
		for at := 0; at < len(values); at += 8 {
			for _, value := range values[at:min(at+8, len(values))] {
				b.WriteString(strconv.FormatFloat(value, 'g', -1, 64) + ", ")
			}

			b.WriteString("\n")
		}
	}

	b.WriteString("// Copyright (c) Nicholas Fedor 2026 <nick@nickfedor.com>\n")
	b.WriteString("// SPDX-License-Identifier: AGPL-3.0-or-later\n\n")
	b.WriteString("// Code generated by go test -run ^TestSynthTables$ -update. DO NOT EDIT.\n\n")
	b.WriteString("package synth\n\n")
	b.WriteString("// lee holds the factors 1/(2 cos(π(2k+1)/(2n))) by which the DCT scales the differences of\n")
	b.WriteString("// each split, rounded to the nearest float64. The 16 factors of 32 points come first, then the\n")
	b.WriteString("// 8 of 16 points, down to the 1 of 2 points.\n")
	b.WriteString("var lee = [dctFactors]float64{\n")
	row(factors[:])
	b.WriteString("}\n\n")
	b.WriteString("// window holds the 512 taps D(i) of the synthesis window, each a multiple of 2^-16.\n")
	b.WriteString("var window = [windowTaps]float64{\n")
	row(taps[:])
	b.WriteString("}\n")

	source, err := format.Source(b.Bytes())
	require.NoError(t, err)

	return source
}
