package generated

import (
	"fmt"
	"go/format"
	"testing"

	"github.com/stretchr/testify/require"
)

// Source returns the source of a generated Go file, formatted as gofmt formats it.
//
// The file starts with the copyright and license header. A notice follows that marks the file
// generated and names the test that rewrites it. Then come the package clause and the body.
//
// Parameters:
//   - tb: the test that generates the file, whose name the notice gives. It fails if the source
//     does not format.
//   - pkg: the name of the file's package.
//   - body: the declarations after the package clause.
//
// Returns:
//   - []byte: the formatted source.
func Source(tb testing.TB, pkg string, body []byte) []byte {
	tb.Helper()

	file := fmt.Appendf(nil, "// Copyright (c) Nicholas Fedor 2026 <nick@nickfedor.com>\n"+
		"// SPDX-License-Identifier: Apache-2.0\n\n"+
		"// Code generated by go test -run ^%s$ -update. DO NOT EDIT.\n\n"+
		"package %s\n\n", tb.Name(), pkg)

	source, err := format.Source(append(file, body...))
	require.NoError(tb, err)

	return source
}
